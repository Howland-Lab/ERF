#!/usr/bin/env python3
"""
make_variants.py -- create the run folders (in ../runs/) for the second ERF week (15 Oct 2026) from the validated decks.

  Gray-zone scan (convective, CPU):  cases/gz_cbl_dx050, dx100, dx200, dx400
      Same physics and closure as cases/cbl_sd25 (Deardorff LES, 4 h), but a 16 km x 16 km domain so that even the
      400 m grid has 40 x 40 columns, and horizontal spacing 50 / 100 / 200 / 400 m (Delta/zi ~ 0.05-0.4, i.e. from LES
      into the grey zone). Vertical spacing stays 20 m (100 levels) so only the horizontal resolution changes.
      Plotfiles every 300 s (13 in the last hour) for distributions.
  Stable ensemble (CPU):  cases/ens_sbl6_s1 ... s5
      cases/sbl_dx6p25 with erf.random_seed = 1..5 (independent initial noise), 3-D output every 120 s for the whole
      run so that statistics can be taken at a fixed time across members as well as over time within a member.
  Convective ensemble (PVC):  cases_pvc/ens_cbl25_s1 ... s4
      cases/cbl_sd25 with erf.random_seed = 1..4; output as the original (plotfiles every 600 s).
Nothing else differs from the decks that were compared against WRF on 13 Oct.
"""
import os, re, shutil

R = os.path.dirname(os.path.abspath(__file__))          # this cases/ folder
RUNS = os.path.join(R, "..", "runs")                      # git-ignored run directories


def setkey(txt, key, val, comment=""):
    pat = re.compile(rf"^(\s*{re.escape(key)}\s*=)[^\n#]*(#.*)?$", re.M)
    line = f"{key} = {val}" + (f"   # {comment}" if comment else "")
    if pat.search(txt):
        return pat.sub(line, txt, count=1)
    return txt.rstrip("\n") + "\n" + line + "\n"


def make(src, dst, changes, header):
    os.makedirs(dst, exist_ok=True)
    txt = open(os.path.join(src, "inputs")).read()
    for k, v, c in changes:
        txt = setkey(txt, k, v, c)
    open(os.path.join(dst, "inputs"), "w").write(f"# {header}\n# generated by make_week2_runs.py from {os.path.relpath(src, R)}\n" + txt)
    shutil.copy(os.path.join(src, "input_sounding"), dst)
    print("made", os.path.relpath(dst, R))


cbl = os.path.join(R, "cbl_sd25")
for dx, mgs in ((50, 20), (100, 20), (200, 20), (400, 10)):
    n = int(16000 / dx)
    make(cbl, os.path.join(RUNS, f"gz_cbl_dx{dx:03d}"),
         [("geometry.prob_extent", "16000 16000 2000", "16 km domain for the whole scan"),
          ("amr.n_cell", f"{n} {n} 100", f"dx = {dx} m, dz = 20 m"),
          ("amr.max_grid_size_x", str(mgs), ""), ("amr.max_grid_size_y", str(mgs), ""),
          ("erf.plot_per_1", "300.0", "13 plotfiles in the last hour"),
          ("erf.plot_vars_1", "x_velocity y_velocity z_velocity theta rhoKE", "")],
         f"grey-zone scan: convective case, dx = {dx} m")

sbl = os.path.join(R, "sbl_dx6p25")
for s in range(1, 6):
    make(sbl, os.path.join(RUNS, f"ens_sbl6_s{s}"),
         [("erf.random_seed", str(s), "independent initial noise for this member"),
          ("erf.plot_per_1", "120.0", "3-D output every 2 min for ensemble statistics"),
          ("erf.plot_vars_1", "x_velocity y_velocity z_velocity theta", "")],
         f"stable ensemble member, seed {s}")

for s in range(1, 5):
    make(cbl, os.path.join(RUNS, f"ens_cbl25_s{s}"),
         [("erf.random_seed", str(s), "independent initial noise for this member")],
         f"convective ensemble member, seed {s}")
